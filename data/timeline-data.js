/**
 * Tiện ích lấy nội dung sự kiện theo ngôn ngữ hiện tại
 */
window.getEventData = function (ev, lang) {
  const l = lang || (window.getCurrentLang ? window.getCurrentLang() : 'vi');
  const isJa = l === 'ja';
  return {
    ...ev,
    title: (isJa && ev.title_ja) ? ev.title_ja : ev.title,
    date: (isJa && ev.date_ja) ? ev.date_ja : ev.date,
    text: (isJa && ev.text_ja) ? ev.text_ja : ev.text,
    note: (isJa && ev.note_ja != null) ? ev.note_ja : ev.note,
    src: (isJa && ev.src_ja) ? ev.src_ja : ev.src,
    modalImgLabel: (isJa && ev.modalImgLabel_ja) ? ev.modalImgLabel_ja : ev.modalImgLabel
  };
};
